import React from 'react';
import { DailySummaryRow } from '../api/reports';
import { formatLKR } from '../../../lib/money';
import { formatReceiptDate } from '../../receipts/lib/formatPlainText';

export interface DailySummarySlipProps {
  rows: DailySummaryRow[];
  dateRangeLabel: string;
  shopName?: string;
  userName?: string;
  paperWidth?: '80mm' | '58mm';
  className?: string;
}

/**
 * Compact Thermal Print Slip for Daily Summary
 * Designed for 80mm and 58mm thermal receipt printers.
 */
export const DailySummarySlip: React.FC<DailySummarySlipProps> = ({
  rows,
  dateRangeLabel,
  shopName = 'Wewala Store',
  userName = 'Manager',
  paperWidth = '80mm',
  className = '',
}) => {
  const printableWidthStyle =
    paperWidth === '58mm' ? 'w-[48mm] max-w-[48mm]' : 'w-[72mm] max-w-[72mm]';

  const totalBills = rows.reduce((s, r) => s + r.bill_count, 0);
  const totalGross = rows.reduce((s, r) => s + BigInt(r.gross_sales_cents), 0n);
  const totalItemDisc = rows.reduce((s, r) => s + BigInt(r.item_discounts_cents), 0n);
  const totalBillDisc = rows.reduce((s, r) => s + BigInt(r.bill_discounts_cents), 0n);
  const totalTax = rows.reduce((s, r) => s + BigInt(r.tax_cents), 0n);
  const totalNet = rows.reduce((s, r) => s + BigInt(r.net_sales_cents), 0n);
  const totalReturns = rows.reduce((s, r) => s + BigInt(r.returns_cents), 0n);
  const finalNet = rows.reduce((s, r) => s + BigInt(r.final_net_cents), 0n);
  const totalCash = rows.reduce((s, r) => s + BigInt(r.cash_cents), 0n);
  const totalCard = rows.reduce((s, r) => s + BigInt(r.card_cents), 0n);
  const totalBt = rows.reduce((s, r) => s + BigInt(r.bank_transfer_cents), 0n);
  const totalSc = rows.reduce((s, r) => s + BigInt(r.store_credit_cents), 0n);

  return (
    <div
      className={`bg-white text-black font-mono text-[11px] leading-tight select-none p-2 mx-auto border border-dashed border-slate-300 shadow-sm print:border-none print:shadow-none print:p-0 ${printableWidthStyle} ${className}`}
      style={{
        width: paperWidth === '58mm' ? '48mm' : '72mm',
      }}
    >
      {/* 1. Header Banner */}
      <div className="text-center font-black text-xs py-1 border-b border-dashed border-black mb-1.5 tracking-wider">
        *** DAILY SUMMARY SLIP ***
      </div>

      {/* 2. Shop Header */}
      <div className="text-center space-y-0.5">
        <h1 className="text-sm font-black uppercase tracking-wider text-black">
          {shopName}
        </h1>
        <p className="text-[10px] text-black">Management Summary Report</p>
      </div>

      {/* 3. Divider */}
      <div className="my-1.5 border-t border-dashed border-black" />

      {/* 4. Metadata */}
      <div className="space-y-0.5 text-[10px]">
        <div className="flex justify-between">
          <span className="font-bold">Period:</span>
          <span className="font-bold">{dateRangeLabel}</span>
        </div>
        <div className="flex justify-between">
          <span>Printed:</span>
          <span>{formatReceiptDate(new Date().toISOString())}</span>
        </div>
        <div className="flex justify-between">
          <span>Generated By:</span>
          <span>{userName}</span>
        </div>
      </div>

      {/* 5. Metrics Breakdown */}
      <div className="my-1.5 border-t border-dashed border-black" />
      <div className="space-y-1 text-[10px]">
        <div className="flex justify-between font-bold">
          <span>Total Transactions:</span>
          <span>{totalBills}</span>
        </div>
        <div className="flex justify-between">
          <span>Gross Sales:</span>
          <span>{formatLKR(totalGross)}</span>
        </div>
        <div className="flex justify-between text-slate-700">
          <span>- Line Discounts:</span>
          <span>-{formatLKR(totalItemDisc)}</span>
        </div>
        <div className="flex justify-between text-slate-700">
          <span>- Bill Discounts:</span>
          <span>-{formatLKR(totalBillDisc)}</span>
        </div>
        <div className="flex justify-between">
          <span>Tax (VAT):</span>
          <span>+{formatLKR(totalTax)}</span>
        </div>
        <div className="flex justify-between font-bold border-t border-dotted border-black/50 pt-0.5">
          <span>Net Sales:</span>
          <span>{formatLKR(totalNet)}</span>
        </div>
        <div className="flex justify-between text-rose-800">
          <span>- Returns / Refunds:</span>
          <span>-{formatLKR(totalReturns)}</span>
        </div>
      </div>

      {/* 6. Grand Final Net Total */}
      <div className="my-1.5 border-t border-dashed border-black" />
      <div className="flex justify-between items-baseline text-xs font-black py-0.5">
        <span className="uppercase">FINAL NET TOTAL:</span>
        <span className="text-sm font-black">{formatLKR(finalNet)}</span>
      </div>

      {/* 7. Payments Breakdown */}
      <div className="my-1.5 border-t border-dashed border-black" />
      <div className="text-[10px] font-bold pb-1 uppercase tracking-wider text-center">
        Payments Collected
      </div>
      <div className="space-y-0.5 text-[10px]">
        <div className="flex justify-between">
          <span>Cash Tendered:</span>
          <span>{formatLKR(totalCash)}</span>
        </div>
        <div className="flex justify-between">
          <span>Card Payments:</span>
          <span>{formatLKR(totalCard)}</span>
        </div>
        <div className="flex justify-between">
          <span>Bank Transfer:</span>
          <span>{formatLKR(totalBt)}</span>
        </div>
        <div className="flex justify-between">
          <span>Store Credit:</span>
          <span>{formatLKR(totalSc)}</span>
        </div>
      </div>

      {/* 8. Footer */}
      <div className="my-2 border-t border-dashed border-black" />
      <div className="text-center text-[9px] text-slate-600 space-y-0.5">
        <p className="font-bold">*** END OF REPORT SLIP ***</p>
        <p>Wewala Super Store • Internal Records</p>
      </div>
    </div>
  );
};

